'use client'

import { useEffect, useState } from 'react'
import type { GeneratedFile } from '@patchbay-nebius/agent'
import type { GhUser } from './github-badge'

interface Repo {
  fullName: string
  owner: string
  name: string
  private: boolean
  defaultBranch: string
}

export function GitHubPush({ user, prompt, files }: { user: GhUser | null; prompt: string; files: GeneratedFile[] }) {
  const [repos, setRepos] = useState<Repo[] | null>(null)
  const [repoFilter, setRepoFilter] = useState('')
  const [selected, setSelected] = useState<string>('')
  const [targetPath, setTargetPath] = useState('connectors/patchbay')
  const [branch, setBranch] = useState('')
  const [pushing, setPushing] = useState(false)
  const [result, setResult] = useState<{ prUrl?: string; error?: string } | null>(null)

  const connected = user?.connected ?? false

  useEffect(() => {
    if (!connected) return
    fetch('/api/github/repos', { cache: 'no-store' })
      .then((r) => r.json())
      .then((d: { repos?: Repo[] }) => {
        setRepos(d.repos ?? [])
        if (d.repos && d.repos.length > 0 && !selected) setSelected(d.repos[0]!.fullName)
      })
      .catch(() => setRepos([]))
  // eslint-disable-next-line react-hooks/exhaustive-deps
  }, [connected])

  useEffect(() => {
    // Default a readable target path from the prompt.
    const slug = prompt
      .toLowerCase()
      .replace(/[^a-z0-9]+/g, '-')
      .replace(/^-|-$/g, '')
      .split('-')
      .slice(0, 4)
      .join('-')
    if (slug) setTargetPath(`connectors/${slug.slice(0, 48)}`)
  }, [prompt])

  if (!user) return null

  if (!connected) {
    return (
      <div className="rounded-xl border border-paper-line bg-paper-card px-4 py-3 text-xs">
        <div className="flex flex-wrap items-center justify-between gap-2">
          <span className="text-ink-soft">Open this run as a pull request in one of your GitHub repos.</span>
          <a href="/api/auth/github" className="rounded-md bg-ink px-3 py-1 text-xs text-white">Connect GitHub</a>
        </div>
      </div>
    )
  }

  const filtered = (repos ?? []).filter((r) => r.fullName.toLowerCase().includes(repoFilter.toLowerCase()))

  async function push() {
    if (!selected || files.length === 0) return
    setPushing(true)
    setResult(null)
    try {
      const res = await fetch('/api/github/push', {
        method: 'POST',
        headers: { 'Content-Type': 'application/json' },
        body: JSON.stringify({
          repo: selected,
          targetPath: targetPath.replace(/^\/+|\/+$/g, '') || 'connectors/patchbay',
          branch: branch.trim() || undefined,
          title: `patchbay: ${prompt.slice(0, 72)}`,
          body: `Generated by [patchbay](https://patchbay-nebius.vercel.app) from the prompt:\n\n> ${prompt}\n\n${files.length} files under \`${targetPath}/\`. Tests pass in a hermetic Nebius sandbox.`,
          files: files.map((f) => ({ path: f.path, content: f.content })),
        }),
      })
      const data = (await res.json()) as { prUrl?: string; error?: string }
      if (!res.ok || data.error) {
        setResult({ error: data.error ?? `Push failed (${res.status})` })
      } else {
        setResult({ prUrl: data.prUrl })
      }
    } catch (error) {
      setResult({ error: error instanceof Error ? error.message : String(error) })
    } finally {
      setPushing(false)
    }
  }

  return (
    <div className="rounded-xl border border-paper-line bg-paper-card p-4">
      <div className="flex items-center justify-between gap-2">
        <h3 className="text-sm font-semibold">Push to your GitHub</h3>
        <span className="text-[11px] text-ink-mute">as @{user.login}</span>
      </div>
      <p className="mt-1 text-xs text-ink-soft">Opens a pull request on your repo with the generated connector files.</p>

      <div className="mt-4 grid gap-3 sm:grid-cols-2">
        <label className="flex flex-col gap-1 text-xs">
          <span className="text-ink-mute">Repository</span>
          <input
            type="text"
            value={repoFilter}
            onChange={(e) => setRepoFilter(e.target.value)}
            placeholder="Filter repos…"
            className="rounded-md border border-paper-line bg-paper px-2 py-1.5 outline-none focus:border-ink-mute"
          />
          <select
            value={selected}
            onChange={(e) => setSelected(e.target.value)}
            className="mt-1 rounded-md border border-paper-line bg-paper px-2 py-1.5 outline-none focus:border-ink-mute"
          >
            {!repos && <option>Loading…</option>}
            {repos && repos.length === 0 && <option>No pushable repos found</option>}
            {filtered.map((r) => (
              <option key={r.fullName} value={r.fullName}>
                {r.fullName}{r.private ? ' · private' : ''}
              </option>
            ))}
          </select>
        </label>
        <label className="flex flex-col gap-1 text-xs">
          <span className="text-ink-mute">Target path in repo</span>
          <input
            type="text"
            value={targetPath}
            onChange={(e) => setTargetPath(e.target.value)}
            placeholder="connectors/stripe-mailchimp"
            className="rounded-md border border-paper-line bg-paper px-2 py-1.5 outline-none focus:border-ink-mute"
          />
          <span className="mt-1 text-ink-mute">Branch (optional)</span>
          <input
            type="text"
            value={branch}
            onChange={(e) => setBranch(e.target.value)}
            placeholder="patchbay/stripe-mailchimp"
            className="rounded-md border border-paper-line bg-paper px-2 py-1.5 outline-none focus:border-ink-mute"
          />
        </label>
      </div>

      <div className="mt-4 flex flex-wrap items-center gap-3">
        <button
          onClick={push}
          disabled={pushing || !selected || files.length === 0}
          className="rounded-md bg-ink px-3 py-1.5 text-xs text-white disabled:opacity-40"
        >
          {pushing ? 'Opening PR…' : 'Open pull request'}
        </button>
        {result?.prUrl && (
          <a href={result.prUrl} target="_blank" rel="noreferrer" className="text-xs text-signal hover:underline">
            {result.prUrl} ↗
          </a>
        )}
        {result?.error && <span className="text-xs text-warn">{result.error}</span>}
      </div>
    </div>
  )
}
