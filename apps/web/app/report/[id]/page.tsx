import { notFound } from 'next/navigation'
import { letterGrade, score, gradeColor } from '@patchbay-nebius/audit-core'
import { loadReport } from '@/lib/report-store'
import type { AuditReport, Finding, Severity } from '@patchbay-nebius/audit-core'

export const runtime = 'nodejs'
export const dynamic = 'force-dynamic'

const SEV_ORDER: Severity[] = ['critical', 'high', 'medium', 'low', 'info']

const SEV_COLOR: Record<Severity, string> = {
  critical: 'text-red-400 border-red-800 bg-red-950/40',
  high: 'text-orange-400 border-orange-800 bg-orange-950/40',
  medium: 'text-yellow-400 border-yellow-800 bg-yellow-950/40',
  low: 'text-neutral-300 border-neutral-800 bg-neutral-900',
  info: 'text-neutral-400 border-neutral-800 bg-neutral-900',
}

export default async function ReportPage({ params }: { params: { id: string } }) {
  const entry = await loadReport(params.id)
  if (!entry) notFound()

  const report = entry.body as AuditReport
  const num = score(report.summary)
  const grade = letterGrade(num)
  const color = gradeColor(grade)

  const grouped = SEV_ORDER.reduce<Record<Severity, Finding[]>>((acc, s) => {
    acc[s] = report.findings.filter((f) => f.severity === s)
    return acc
  }, { critical: [], high: [], medium: [], low: [], info: [] })

  return (
    <main className="mx-auto max-w-3xl px-6 py-12 text-neutral-200">
      <div className="mb-8">
        <p className="text-sm text-neutral-500">patchbay audit report</p>
        <h1 className="mt-1 text-2xl font-semibold text-white break-all">{report.target}</h1>
        <p className="mt-2 text-sm text-neutral-500">
          Captured {new Date(entry.storedAt).toLocaleString()} · {(report.durationMs / 1000).toFixed(1)}s
        </p>
      </div>

      <div className="mb-10 flex items-center gap-6 rounded border border-neutral-800 bg-neutral-950 p-6">
        <div
          className="flex h-20 w-20 items-center justify-center rounded text-3xl font-bold text-white"
          style={{ backgroundColor: color }}
        >
          {grade}
        </div>
        <div>
          <p className="text-3xl font-semibold text-white">{num} / 100</p>
          <p className="mt-1 text-sm text-neutral-400">
            {SEV_ORDER.filter((s) => report.summary[s] > 0)
              .map((s) => `${report.summary[s]} ${s}`)
              .join(' · ') || 'all clean'}
          </p>
        </div>
      </div>

      <div className="mb-10 rounded border border-neutral-800 bg-neutral-950 p-4">
        <p className="mb-2 text-sm font-medium text-neutral-100">Embed this badge:</p>
        <pre className="overflow-x-auto rounded bg-neutral-950 p-3 text-xs text-neutral-300">
{`[![patchbay](https://patchbay-mcp.dev/api/badge/${encodeURIComponent(report.target)}.svg)](https://patchbay-mcp.dev/report/${entry.id})`}
        </pre>
        <img
          src={`/api/badge/${encodeURIComponent(report.target)}.svg`}
          alt="patchbay badge"
          className="mt-3 h-6"
        />
      </div>

      {report.findings.length === 0 ? (
        <p className="text-neutral-400">No findings.</p>
      ) : (
        SEV_ORDER.map((sev) =>
          grouped[sev].length ? (
            <section key={sev} className="mb-10">
              <h2 className="mb-3 text-lg font-semibold capitalize text-white">{sev}</h2>
              <div className="space-y-4">
                {grouped[sev].map((f, i) => (
                  <article key={i} className={`rounded border p-4 ${SEV_COLOR[sev]}`}>
                    <h3 className="font-semibold">
                      {f.id} <span className="text-neutral-400">—</span> {f.title}
                    </h3>
                    <p className="mt-2 whitespace-pre-wrap text-sm text-neutral-300">{f.evidence}</p>
                    <p className="mt-3 text-sm text-neutral-100">
                      <span className="font-medium">Fix:</span> {f.fix}
                    </p>
                    <p className="mt-2 text-xs text-neutral-500">
                      Severity {f.severity} · Confidence {f.confidence} ·{' '}
                      <a href={f.docsUrl} className="underline underline-offset-4 hover:text-neutral-200">
                        docs
                      </a>
                    </p>
                  </article>
                ))}
              </div>
            </section>
          ) : null,
        )
      )}

      <footer className="mt-16 border-t border-neutral-800 pt-6 text-sm text-neutral-500">
        <p>
          Generated by{' '}
          <a href="https://patchbay-mcp.dev" className="text-neutral-300 underline underline-offset-4">
            patchbay audit
          </a>
          . Reproduce:
        </p>
        <pre className="mt-2 overflow-x-auto rounded bg-neutral-950 p-3 text-xs">
          {`npx -y @patchbay-nebius/agent audit ${report.target}`}
        </pre>
      </footer>
    </main>
  )
}
