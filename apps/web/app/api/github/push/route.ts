import { readSession } from '@/lib/github-session'

export const runtime = 'nodejs'
export const dynamic = 'force-dynamic'

interface PushBody {
  repo: string
  targetPath: string
  branch?: string
  title?: string
  body?: string
  files: { path: string; content: string }[]
}

/**
 * Push a connector drop into the user's repo as a pull request.
 * Caller sends the files inline (the web demo has them in state after a build)
 * so we don't need any run artifacts on disk — Vercel's lambdas are read-only.
 */
export async function POST(request: Request) {
  const session = await readSession()
  if (!session) return Response.json({ error: 'not_connected' }, { status: 401 })

  const body = (await request.json().catch(() => null)) as PushBody | null
  if (!body) return Response.json({ error: 'bad_body' }, { status: 400 })
  const { repo, targetPath, files } = body
  if (!repo?.includes('/')) return Response.json({ error: 'bad_repo' }, { status: 400 })
  if (!targetPath || !Array.isArray(files) || files.length === 0) {
    return Response.json({ error: 'nothing_to_push' }, { status: 400 })
  }
  // Reject path traversal before we join it with a filename and ask GitHub to
  // commit it. GitHub rejects most of these upstream, but trusting that is
  // the kind of defence-in-depth miss that owns you later.
  const normalizedTargetPath = targetPath.replace(/\\/g, '/').replace(/\/+/g, '/').replace(/^\/+|\/+$/g, '')
  if (!normalizedTargetPath || normalizedTargetPath.split('/').some(seg => seg === '..' || seg === '.')) {
    return Response.json({ error: 'bad_target_path' }, { status: 400 })
  }
  for (const f of files) {
    const p = f.path.replace(/\\/g, '/').replace(/\/+/g, '/')
    if (p.startsWith('/') || p.split('/').some(seg => seg === '..' || seg === '.')) {
      return Response.json({ error: 'bad_file_path', detail: f.path }, { status: 400 })
    }
  }

  const [owner, name] = repo.split('/')
  const token = session.accessToken
  const api = createApi(token)

  try {
    const repoInfo = (await api(`/repos/${owner}/${name}`)) as { default_branch: string }
    const base = repoInfo.default_branch
    const branch = body.branch?.trim() || `patchbay/${Date.now().toString(36)}`

    const baseRef = (await api(`/repos/${owner}/${name}/git/ref/heads/${base}`)) as { object: { sha: string } }
    try {
      await api(`/repos/${owner}/${name}/git/refs`, {
        method: 'POST',
        body: { ref: `refs/heads/${branch}`, sha: baseRef.object.sha },
      })
    } catch (error) {
      if (!/already exists/i.test(String(error))) throw error
    }

    for (const file of files) {
      const path = `${targetPath}/${file.path}`.replace(/\\/g, '/').replace(/\/+/g, '/')
      const existing = (await api(`/repos/${owner}/${name}/contents/${encodePath(path)}?ref=${branch}`).catch(() => null)) as { sha?: string } | null
      await api(`/repos/${owner}/${name}/contents/${encodePath(path)}`, {
        method: 'PUT',
        body: {
          message: `patchbay: ${path}`,
          content: Buffer.from(file.content, 'utf8').toString('base64'),
          branch,
          ...(existing?.sha ? { sha: existing.sha } : {}),
        },
      })
    }

    const title = body.title?.trim() || `patchbay: ${targetPath}`
    const prBody = body.body?.trim() || `Generated by [patchbay](https://patchbay-nebius.vercel.app) — ${files.length} files under \`${targetPath}/\`. Tests pass against the documented example in a hermetic sandbox.`
    const pr = (await api(`/repos/${owner}/${name}/pulls`, {
      method: 'POST',
      body: { title, head: branch, base, body: prBody, draft: false },
    })) as { html_url: string; number: number }

    return Response.json({ ok: true, prUrl: pr.html_url, prNumber: pr.number, branch, base })
  } catch (error) {
    return Response.json({ error: error instanceof Error ? error.message : String(error) }, { status: 400 })
  }
}

function encodePath(path: string): string {
  return path.split('/').map(encodeURIComponent).join('/')
}

function createApi(token: string) {
  return async <T = unknown>(path: string, init: { method?: string; body?: unknown } = {}): Promise<T> => {
    const res = await fetch(`https://api.github.com${path}`, {
      method: init.method ?? 'GET',
      headers: {
        Authorization: `Bearer ${token}`,
        Accept: 'application/vnd.github+json',
        'X-GitHub-Api-Version': '2022-11-28',
        'User-Agent': 'patchbay-web',
        ...(init.body ? { 'Content-Type': 'application/json' } : {}),
      },
      body: init.body ? JSON.stringify(init.body) : undefined,
    })
    const text = await res.text()
    const data = text ? JSON.parse(text) : {}
    if (!res.ok) throw new Error(`GitHub ${init.method ?? 'GET'} ${path}: HTTP ${res.status} ${(data as { message?: string }).message ?? text.slice(0, 200)}`)
    return data as T
  }
}
