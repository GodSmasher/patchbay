import { describe, expect, it } from 'vitest'
import type { AuditReport, Finding } from '../types'
import { renderMarkdown } from './markdown'

function finding(overrides: Partial<Finding> = {}): Finding {
  return {
    id: 'AUTH-001',
    severity: 'critical',
    confidence: 'high',
    title: 'No authentication required',
    evidence: 'tools/list returned 6 tool(s) without credentials.',
    fix: 'Require OAuth 2.1.',
    docsUrl: 'https://patchbay-mcp.dev/docs/auth-001',
    ...overrides,
  }
}

function report(findings: Finding[]): AuditReport {
  const summary = { critical: 0, high: 0, medium: 0, low: 0, info: 0 }
  for (const f of findings) summary[f.severity]++
  return {
    target: 'https://mcp.example.com/mcp',
    kind: 'remote-url',
    findings,
    summary,
    durationMs: 1800,
    capturedAt: '2026-11-03T10:00:00Z',
    snapshot: {
      kind: 'remote-url',
      target: 'https://mcp.example.com/mcp',
      capturedAt: '2026-11-03T10:00:00Z',
    },
  }
}

describe('renderMarkdown', () => {
  it('emits a title, target, and reproducer footer by default', () => {
    const md = renderMarkdown(report([]))
    expect(md).toContain('# patchbay audit')
    expect(md).toContain('`https://mcp.example.com/mcp`')
    expect(md).toContain('Generated by [patchbay audit]')
    expect(md).toContain('npx -y @patchbay-nebius/agent audit https://mcp.example.com/mcp')
  })

  it('says "all clean" when no findings', () => {
    const md = renderMarkdown(report([]))
    expect(md).toContain('all clean')
    expect(md).toContain('No findings.')
  })

  it('groups findings by severity, critical first', () => {
    const md = renderMarkdown(report([
      finding({ id: 'LOW-1', severity: 'low', title: 'Low thing' }),
      finding({ id: 'CRIT-1', severity: 'critical', title: 'Critical thing' }),
      finding({ id: 'INFO-1', severity: 'info', title: 'Info thing' }),
    ]))
    const posCrit = md.indexOf('## Critical')
    const posLow = md.indexOf('## Low')
    const posInfo = md.indexOf('## Info')
    expect(posCrit).toBeGreaterThan(0)
    expect(posCrit).toBeLessThan(posLow)
    expect(posLow).toBeLessThan(posInfo)
  })

  it('renders summary table when findings exist', () => {
    const md = renderMarkdown(report([
      finding({ severity: 'critical' }),
      finding({ id: 'AUTH-002', severity: 'high' }),
    ]))
    expect(md).toContain('| Severity | Count |')
    expect(md).toContain('| Critical | 1 |')
    expect(md).toContain('| High | 1 |')
  })

  it('escapes multi-line evidence into a blockquote', () => {
    const md = renderMarkdown(report([
      finding({ evidence: 'line one\nline two\nline three' }),
    ]))
    expect(md).toContain('> line one')
    expect(md).toContain('> line two')
    expect(md).toContain('> line three')
  })

  it('includes severity and confidence per finding', () => {
    const md = renderMarkdown(report([
      finding({ severity: 'medium', confidence: 'low' }),
    ]))
    expect(md).toContain('**Severity:** medium · **Confidence:** low')
  })

  it('includes the finding docs url as an auto-link', () => {
    const md = renderMarkdown(report([finding()]))
    expect(md).toContain('<https://patchbay-mcp.dev/docs/auth-001>')
  })

  it('footer can be disabled', () => {
    const md = renderMarkdown(report([finding()]), { footer: false })
    expect(md).not.toContain('Generated by')
  })

  it('footer tool string is overridable', () => {
    const md = renderMarkdown(report([finding()]), { toolString: 'patchbay audit v0.1.3' })
    expect(md).toContain('[patchbay audit v0.1.3]')
  })

  it('is deterministic for the same input', () => {
    const r = report([finding()])
    expect(renderMarkdown(r)).toBe(renderMarkdown(r))
  })
})
