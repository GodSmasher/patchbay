import type { AuditReport, Finding, Severity } from '../types'

/**
 * Markdown reporter: produces a PR-body-ready document.
 *
 * Grouped by severity (critical first), with a summary table at the top,
 * reproducer command per finding, and a footer identifying the tool and run.
 *
 * Designed to be dropped into a PR body or committed as PATCHBAY_AUDIT.md
 * in a target repo. No ANSI colors, no CTA, no interactive bits.
 */

const SEV_ORDER: Severity[] = ['critical', 'high', 'medium', 'low', 'info']
const SEV_ICON: Record<Severity, string> = {
  critical: 'critical',
  high: 'high',
  medium: 'medium',
  low: 'low',
  info: 'info',
}

export interface MarkdownReportOptions {
  /** Include the "Generated by patchbay audit" footer. Defaults to true. */
  footer?: boolean
  /** Override the tool/version string in the footer. */
  toolString?: string
}

export function renderMarkdown(report: AuditReport, opts: MarkdownReportOptions = {}): string {
  const lines: string[] = []

  lines.push(`# patchbay audit`)
  lines.push('')
  lines.push(`**Target:** \`${report.target}\``)
  lines.push(`**Captured:** ${report.capturedAt}`)
  lines.push(`**Duration:** ${(report.durationMs / 1000).toFixed(1)}s`)
  lines.push('')

  lines.push(summaryTable(report))
  lines.push('')

  if (report.findings.length === 0) {
    lines.push('No findings.')
    lines.push('')
  } else {
    const grouped = groupBySeverity(report.findings)
    for (const sev of SEV_ORDER) {
      const items = grouped[sev]
      if (!items.length) continue
      lines.push(`## ${capitalise(sev)}`)
      lines.push('')
      for (const f of items) lines.push(...renderFinding(f, report.target))
    }
  }

  if (opts.footer !== false) {
    lines.push('---')
    lines.push('')
    lines.push(`Generated by [${opts.toolString ?? 'patchbay audit'}](https://patchbay-mcp.dev).`)
    lines.push(`Reproduce: \`npx -y @patchbay-nebius/agent audit ${report.target}\``)
    lines.push('')
  }

  return lines.join('\n')
}

function summaryTable(report: AuditReport): string {
  const rows = SEV_ORDER
    .filter((s) => report.summary[s] > 0)
    .map((s) => `| ${capitalise(s)} | ${report.summary[s]} |`)
  if (!rows.length) return '**Summary:** all clean.'
  return ['| Severity | Count |', '|---|---|', ...rows].join('\n')
}

function renderFinding(f: Finding, target: string): string[] {
  const out: string[] = []
  out.push(`### ${f.id} — ${f.title}`)
  out.push('')
  out.push(`**Severity:** ${f.severity} · **Confidence:** ${f.confidence}`)
  out.push('')
  out.push('**What we found:**')
  out.push('')
  out.push(`> ${f.evidence.split('\n').join('\n> ')}`)
  out.push('')
  out.push('**Suggested fix:**')
  out.push('')
  out.push(f.fix)
  out.push('')
  out.push(`**Reproduce:** \`npx -y @patchbay-nebius/agent audit ${target}\``)
  out.push('')
  out.push(`**Docs:** <${f.docsUrl}>`)
  out.push('')
  return out
}

function groupBySeverity(findings: Finding[]): Record<Severity, Finding[]> {
  const out: Record<Severity, Finding[]> = { critical: [], high: [], medium: [], low: [], info: [] }
  for (const f of findings) out[f.severity].push(f)
  return out
}

function capitalise(s: string): string {
  return s.charAt(0).toUpperCase() + s.slice(1)
}

// Keep icon map exported for future reuse by other UIs; silence noUnusedLocals.
void SEV_ICON
