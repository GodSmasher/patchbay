import { readdirSync, readFileSync, statSync } from 'node:fs'
import { join, relative } from 'node:path'

export interface PushOptions {
  runDir: string
  repo: string                    // "owner/name"
  token: string
  /** Where inside the target repo the connector files land. */
  targetPath: string              // e.g. "connectors/typeform-pipedrive"
  /** Branch to create. Defaults to patchbay/<basename(runDir)>. */
  branch?: string
  /** Base branch to branch from. GitHub defaults it to the repo's default. */
  base?: string
  /** PR title + body overrides. */
  title?: string
  body?: string
  /** Set true to log what would happen without hitting the API. */
  dryRun?: boolean
}

export interface PushResult {
  prUrl: string
  branch: string
  base: string
  files: string[]
}

const API = 'https://api.github.com'

/**
 * Takes a recorded patchbay run (runs/<timestamp>/ with src/* + README.md) and lands it in a
 * target GitHub repo as a pull request: new branch, commits every file under `targetPath`,
 * opens a PR against the repo's default branch.
 *
 * Uses the GitHub REST API directly (fetch + token). The token needs `repo` scope on the
 * target. Dry-run prints the plan without calling the API.
 */
export async function pushToGitHub(opts: PushOptions): Promise<PushResult> {
  const files = collectRunFiles(opts.runDir)
  if (files.length === 0) {
    throw new Error(`${opts.runDir} has no files to push (expected src/* and README.md for TS, or connector.py + test_connector.py + fixtures.py + README.md for Python).`)
  }

  const [owner, name] = opts.repo.split('/')
  if (!owner || !name) throw new Error(`Expected --repo=owner/name, got "${opts.repo}"`)

  const branch = opts.branch ?? `patchbay/${basenameNoSlash(opts.runDir)}`
  const title = opts.title ?? `patchbay: ${opts.targetPath}`
  const body =
    opts.body ??
    `Generated by [patchbay](https://github.com/GodSmasher/patchbay) from \`${basenameNoSlash(opts.runDir)}\`.\n\n` +
      `Includes ${files.length} files under \`${opts.targetPath}/\`. Tests pass against the documented example in a hermetic sandbox.`

  if (opts.dryRun) {
    return { prUrl: `(dry-run) would open PR on ${opts.repo}`, branch, base: opts.base ?? '(default)', files: files.map((f) => f.path) }
  }

  const api = createApi(opts.token)
  const repo = (await api(`/repos/${owner}/${name}`)) as { default_branch: string }
  const base = opts.base ?? repo.default_branch
  const baseRef = (await api(`/repos/${owner}/${name}/git/ref/heads/${base}`)) as { object: { sha: string } }
  const baseSha = baseRef.object.sha

  // Create the branch (409 if it already exists, we tolerate that).
  try {
    await api(`/repos/${owner}/${name}/git/refs`, {
      method: 'POST',
      body: { ref: `refs/heads/${branch}`, sha: baseSha },
    })
  } catch (error) {
    if (!/already exists/i.test(String(error))) throw error
  }

  // One commit per file keeps the diff readable; could be batched into a tree later if it matters.
  for (const file of files) {
    const path = `${opts.targetPath}/${file.path}`.replace(/\\/g, '/')
    const existing = (await api(`/repos/${owner}/${name}/contents/${encodeURIComponent(path)}?ref=${branch}`).catch(() => null)) as { sha?: string } | null
    await api(`/repos/${owner}/${name}/contents/${encodeURIComponent(path)}`, {
      method: 'PUT',
      body: {
        message: `patchbay: ${path}`,
        content: Buffer.from(file.content, 'utf8').toString('base64'),
        branch,
        ...(existing?.sha ? { sha: existing.sha } : {}),
      },
    })
  }

  const pr = (await api(`/repos/${owner}/${name}/pulls`, {
    method: 'POST',
    body: { title, head: branch, base, body, draft: false },
  })) as { html_url: string }

  return { prUrl: pr.html_url, branch, base, files: files.map((f) => f.path) }
}

interface RunFile {
  path: string
  content: string
}

function collectRunFiles(root: string): RunFile[] {
  const out: RunFile[] = []
  const walk = (dir: string) => {
    for (const entry of readdirSync(dir)) {
      if (entry === 'run.json' || entry.startsWith('.')) continue
      const abs = join(dir, entry)
      const st = statSync(abs)
      if (st.isDirectory()) walk(abs)
      else out.push({ path: relative(root, abs).replace(/\\/g, '/'), content: readFileSync(abs, 'utf8') })
    }
  }
  walk(root)
  return out
}

function basenameNoSlash(path: string): string {
  return path.replace(/[\\/]+$/, '').split(/[\\/]/).pop() ?? 'run'
}

function createApi(token: string) {
  return async <T = unknown>(path: string, init: { method?: string; body?: unknown } = {}): Promise<T> => {
    const res = await fetch(`${API}${path}`, {
      method: init.method ?? 'GET',
      headers: {
        Authorization: `Bearer ${token}`,
        Accept: 'application/vnd.github+json',
        'X-GitHub-Api-Version': '2022-11-28',
        'User-Agent': 'patchbay-cli',
        ...(init.body ? { 'Content-Type': 'application/json' } : {}),
      },
      body: init.body ? JSON.stringify(init.body) : undefined,
    })
    const text = await res.text()
    const data = text ? JSON.parse(text) : {}
    if (!res.ok) throw new Error(`GitHub ${init.method ?? 'GET'} ${path}: HTTP ${res.status} ${(data as { message?: string }).message ?? text.slice(0, 200)}`)
    return data as T
  }
}
